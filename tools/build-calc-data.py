"""Data for the reconstitution calculator (calculator.html). Run from the
repo root after adding or renaming products:
    python3 tools/build-calc-data.py

Writes js/calc-data.js (each powder product's vial strengths, and what's in
each blend) and adds a "Reconstitution calculator" link to each matching
product page.
"""
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, 'data'))
import compounds as D  # noqa: E402

LINK_MARK = 'calc-link'


def parse_amount(label):
    m = re.match(r'^\s*([\d.]+)\s*(mg|mcg|iu)\s*$', label, re.I)
    if not m:
        return None
    unit = m.group(2).lower()
    return {'label': label, 'amount': float(m.group(1)), 'unit': 'IU' if unit == 'iu' else unit}


def parse_blend(text):
    if not text:
        return None
    text = re.sub(r'\s*per vial.*$', '', text)
    parts = []
    for piece in text.split('+'):
        m = re.match(r'^\s*([\d.]+)\s*mg\s+(.+?)\s*$', piece)
        if not m:
            return None
        name = m.group(2)
        parts.append({'name': name[0].upper() + name[1:], 'mg': float(m.group(1))})
    return parts if len(parts) > 1 else None


def main():
    cat = json.load(open(os.path.join(ROOT, 'functions', 'catalog.json')))['products']
    out = []
    for slug, p in sorted(cat.items(), key=lambda kv: kv[1]['name'].lower()):
        if p.get('doses'):
            strengths = [parse_amount(d['label']) for d in p['doses'].values()]
        else:
            m = re.search(r'x\s*([\d.]+\s*(?:mg|mcg|iu))\b', p['packSize'], re.I)
            strengths = [parse_amount(m.group(1))] if m else []
        strengths = [s for s in strengths if s]
        if not strengths:
            continue  # liquids (waters, B12, Lipo-C ...) need no reconstitution
        name = p['name'][0].upper() + p['name'][1:]
        item = {'slug': slug, 'name': name, 'strengths': strengths}
        blend = parse_blend((D.P.get(slug) or {}).get('blend'))
        if blend and len(strengths) == 1:
            item['blend'] = blend
        out.append(item)

    js = ('// Generated by tools/build-calc-data.py — do not edit by hand.\n'
          'var CALC_PRODUCTS = ' + json.dumps(out, indent=1) + ';\n')
    open(os.path.join(ROOT, 'js', 'calc-data.js'), 'w', encoding='utf-8').write(js)

    linked = 0
    for item in out:
        path = os.path.join(ROOT, 'products', item['slug'] + '.html')
        if not os.path.exists(path):
            continue
        s = open(path, encoding='utf-8').read()
        s = re.sub(r'\n\s*<a href="\.\./calculator\.html[^"]*" class="' + LINK_MARK + r'">.*?</a>', '', s)
        anchor = re.search(r'(<a href="\.\./contact\.html" class="btn-outline-light"[^>]*>Ask about this product</a>)', s)
        if not anchor:
            print('no contact button on', item['slug'])
            continue
        link = ('\n      <a href="../calculator.html?p=' + item['slug'] + '" class="' + LINK_MARK + '">'
                'Reconstitution calculator &rarr;</a>')
        s = s[:anchor.end()] + link + s[anchor.end():]
        open(path, 'w', encoding='utf-8').write(s)
        linked += 1
    print(len(out), 'products in js/calc-data.js;', linked, 'product pages linked.')


if __name__ == '__main__':
    main()
